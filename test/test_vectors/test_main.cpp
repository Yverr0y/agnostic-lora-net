// Deterministic controller keypair the signed vectors were built with.
static void ctrl_keys(uint8_t sk[64], uint8_t pk[32]) {
    uint8_t seed[32];
    for (int i = 0; i < 32; i++) seed[i] = (uint8_t)(i * 7 + 1);
    crypto_ed25519_key_pair(sk, pk, seed);
}

static const node_id_t VTARGET = nid_from_u32(0x22222222u);
static const node_id_t VVICTIM = nid_from_u32(0x33333333u);

// --- announce ---------------------------------------------------------------
static void test_vec_announce() {
    Announce a;
    TEST_ASSERT_TRUE(announce_deserialize(VEC_ANNOUNCE, sizeof(VEC_ANNOUNCE), a));
    TEST_ASSERT_EQUAL_UINT8(2, a.n_reports);
    TEST_ASSERT_EQUAL_UINT8(2, a.n_routes);
    TEST_ASSERT_EQUAL_HEX16(CAP_SELECTIVE_ACK | CAP_SESSION_ADDR, a.caps);
    TEST_ASSERT_TRUE(a.reports[0].id == nid_from_u32(0xAAAAAAAAu));
    TEST_ASSERT_TRUE(a.routes[1].dst == nid_from_u32(0xCCCCCCCCu));

    // Re-encode must reproduce the golden bytes exactly.
    uint8_t buf[256];
    // origin isn't on the wire; rebuild the same struct the vector came from.
    Announce s; s.origin = nid_from_u32(0x11111111u);
    s.reports[0] = {nid_from_u32(0xAAAAAAAAu), 0.80f, 3};
    s.reports[1] = {nid_from_u32(0xBBBBBBBBu), 0.20f, 7}; s.n_reports = 2;
    s.routes[0] = {nid_from_u32(0xAAAAAAAAu), nid_from_u32(0xAAAAAAAAu), 1.5f, 1};
    s.routes[1] = {nid_from_u32(0xCCCCCCCCu), nid_from_u32(0xBBBBBBBBu), 3.25f, 2}; s.n_routes = 2;
    s.caps = CAP_SELECTIVE_ACK | CAP_SESSION_ADDR;
    uint16_t n = announce_serialize(s, buf, sizeof(buf));
    TEST_ASSERT_EQUAL_UINT16(sizeof(VEC_ANNOUNCE), n);
    TEST_ASSERT_EQUAL_MEMORY(VEC_ANNOUNCE, buf, n);
}

// --- control (signed) -------------------------------------------------------
static void test_vec_control() {
    uint8_t sk[64], pk[32]; ctrl_keys(sk, pk);
    CtrlMsg m;

    TEST_ASSERT_EQUAL(CTRL_OK, ctrl_verify(VEC_CTRL_POWER, sizeof(VEC_CTRL_POWER), pk, 0, &m));
    TEST_ASSERT_EQUAL_UINT8(CTRL_POWER, m.cmd);
    TEST_ASSERT_EQUAL_INT8(14, m.arg);
    TEST_ASSERT_EQUAL_UINT32(7, m.counter);
    TEST_ASSERT_TRUE(m.target == VTARGET);

    TEST_ASSERT_EQUAL(CTRL_OK, ctrl_verify(VEC_CTRL_BLOCK, sizeof(VEC_CTRL_BLOCK), pk, 0, &m));
    TEST_ASSERT_EQUAL_UINT8(CTRL_BLOCK, m.cmd);
    TEST_ASSERT_TRUE(m.aux == VVICTIM);

    TEST_ASSERT_EQUAL(CTRL_OK, ctrl_verify(VEC_CTRL_RETUNE, sizeof(VEC_CTRL_RETUNE), pk, 0, &m));
    TEST_ASSERT_EQUAL_UINT8(CTRL_RETUNE, m.cmd);

    // Re-sign must reproduce the golden bytes (deterministic Ed25519).
    uint8_t buf[128];
    uint16_t n = ctrl_build(CTRL_POWER, VTARGET, 14, 7, sk, buf, sizeof(buf));
    TEST_ASSERT_EQUAL_UINT16(sizeof(VEC_CTRL_POWER), n);
    TEST_ASSERT_EQUAL_MEMORY(VEC_CTRL_POWER, buf, n);
}

// --- telemetry --------------------------------------------------------------
static void test_vec_telemetry() {
    TelemMsg m;
    TEST_ASSERT_TRUE(telem_parse(VEC_TELEM_BATT, sizeof(VEC_TELEM_BATT), &m));
    TEST_ASSERT_EQUAL_UINT8(TELEM_BATT, m.kind);
    TEST_ASSERT_EQUAL_UINT16(3712, m.mv);

    TEST_ASSERT_TRUE(telem_parse(VEC_TELEM_QUERY, sizeof(VEC_TELEM_QUERY), &m));
    TEST_ASSERT_EQUAL_UINT8(TELEM_QUERY, m.kind);
    TEST_ASSERT_TRUE(m.target == VTARGET);

    TEST_ASSERT_TRUE(telem_parse(VEC_TELEM_REPLY, sizeof(VEC_TELEM_REPLY), &m));
    TEST_ASSERT_EQUAL_UINT8(TELEM_REPLY, m.kind);
    TEST_ASSERT_EQUAL_UINT8(2, m.n_nbrs);
    TEST_ASSERT_EQUAL_STRING("0.15.0", m.fw);
    TEST_ASSERT_EQUAL_STRING("bench-node", m.name);

    uint8_t buf[128];
    uint16_t n = telem_build_batt(3712, 88, buf, sizeof(buf));
    TEST_ASSERT_EQUAL_UINT16(sizeof(VEC_TELEM_BATT), n);
    TEST_ASSERT_EQUAL_MEMORY(VEC_TELEM_BATT, buf, n);
}

