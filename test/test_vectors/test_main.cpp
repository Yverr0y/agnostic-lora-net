// Golden wire vectors (handoff plan Task 2, item 5).
//
//   pio test -e native
//
// Checked-in canonical byte sequences for every packet type, each verified two
// ways:
//   1. decode(golden) yields the expected structured fields  (the parser reads
//      the frozen format correctly), and
//   2. encode(fields) reproduces golden byte-for-byte           (the ENCODER
//      hasn't silently drifted — the compatibility contract).
//
// Together these pin the wire format. When the format is eventually frozen,
// these vectors ARE the contract; until then, any intended format change must
// update the bytes here in the same commit, which makes the change reviewable
// as a diff of real bytes. The same canonical bytes seed the fuzzers
// (fuzz/corpus). See docs/wire-format.md.
//
// The vectors are produced by a deterministic keypair (seed[i] = i*7+1) so the
// signed ones (control) are reproducible; regenerate with the host helper noted
// in docs/wire-format.md if the format changes intentionally.

